"""Export an independent long-rollout navigation calibration dataset.

This utility is intended for the strict shared-manifold pipeline.  The ordinary
``nav_eval_arrays.npz`` generated by Exp1 follows the training sequence length
(20 steps in ``nav_pretrain_full.yaml``) and is therefore incompatible with the
50-step recurrent burn-in used by the torus analysis.  This command reloads the
locked navigation checkpoint, generates a disjoint set of long trajectories, and
stores the fields required by ``analyze_shared_manifold``.

By default only the grid-module units selected by ``analyze_torus`` are saved.
The file records their original global indices in ``unit_indices``; the shared-
manifold loader maps them back to the requested source units exactly.  This keeps
the calibration artifact substantially smaller than a full 4096-unit export.
"""
from __future__ import annotations

import argparse
from pathlib import Path
from typing import Optional

import numpy as np
import torch
from torch.utils.data import DataLoader

from gpm_cmap.data.nav_env.dataset import NavDatasetConfig, NavTrajectoryDataset
from gpm_cmap.data.nav_env.open_field import OpenFieldConfig
from gpm_cmap.models.grid_rnn import GridNavigationModel
from gpm_cmap.utils import (
    configure_runtime,
    load_config,
    make_worker_init_fn,
    prepare_output_dir,
    save_config_snapshot,
    save_run_provenance,
    set_seed,
    write_json,
)
from gpm_cmap.utils.checkpointing import load_checkpoint, sha256_file
from gpm_cmap.utils.logging_utils import get_logger


def _load_selected_units(nav_analysis_dir: Optional[str | Path]) -> Optional[np.ndarray]:
    if nav_analysis_dir is None:
        return None
    arrays_path = Path(nav_analysis_dir) / "torus_analysis_arrays.npz"
    if not arrays_path.exists():
        raise FileNotFoundError(
            f"Missing {arrays_path}; pass the formal analyze_torus output directory"
        )
    with np.load(arrays_path, allow_pickle=False) as archive:
        if "selected_unit_indices" not in archive:
            raise KeyError(f"{arrays_path} lacks selected_unit_indices")
        selected = np.asarray(archive["selected_unit_indices"], dtype=np.int64).reshape(-1)
    if selected.size < 2:
        raise ValueError("At least two selected navigation units are required")
    if np.unique(selected).size != selected.size:
        raise ValueError("selected_unit_indices contains duplicates")
    return selected


def _make_loader(
    cfg: dict,
    *,
    num_trajectories: int,
    seq_len: int,
    batch_size: int,
    trajectory_seed: int,
) -> DataLoader:
    open_field = OpenFieldConfig(
        arena_size=cfg["data"]["arena_size"],
        dt=cfg["data"].get("dt", 0.05),
        speed_scale=cfg["data"].get("speed_scale", 0.13),
        sigma_theta=cfg["data"].get("sigma_theta", 5.0),
        max_speed=cfg["data"].get("max_speed", 0.5),
        border_region=cfg["data"].get("border_region", 0.03),
        boundary_mode=cfg["data"].get("boundary_mode", "avoid"),
    )
    dataset = NavTrajectoryDataset(
        NavDatasetConfig(
            num_trajectories=int(num_trajectories),
            seq_len=int(seq_len),
            open_field=open_field,
            place_cells=cfg["data"]["place_cells"],
            place_sigma=cfg["data"]["place_sigma"],
            arena_size=cfg["data"]["arena_size"],
            seed=int(cfg["seed"]),
            trajectory_seed=int(trajectory_seed),
            place_seed=int(cfg["seed"]),
            use_dog=cfg["data"].get("use_dog", True),
            surround_scale=cfg["data"].get("surround_scale", 2.0),
            surround_scale_mode=cfg["data"].get("surround_scale_mode", "variance"),
        )
    )
    return DataLoader(
        dataset,
        batch_size=min(int(batch_size), int(num_trajectories)),
        shuffle=False,
        num_workers=int(cfg["data"].get("num_workers", 0)),
        worker_init_fn=make_worker_init_fn(int(trajectory_seed)),
    )


def _make_model(cfg: dict, device: torch.device) -> GridNavigationModel:
    return GridNavigationModel(
        velocity_dim=cfg["model"]["velocity_dim"],
        hidden_dim=cfg["model"]["hidden_dim"],
        place_dim=cfg["data"]["place_cells"],
        activation=cfg["model"]["activation"],
        nonnegative=cfg["model"]["nonnegative"],
        cell_type=cfg["model"].get("cell_type", "rnn"),
        dropout=cfg["model"].get("dropout", 0.0),
        use_bias=cfg["model"].get("use_bias", False),
        init_relu=cfg["model"].get("init_relu", False),
    ).to(device)


@torch.no_grad()
def _extract_arrays(
    model: torch.nn.Module,
    loader: DataLoader,
    device: torch.device,
    *,
    selected_units: Optional[np.ndarray],
) -> dict[str, np.ndarray]:
    model.eval()
    positions = []
    hidden = []
    headings = []
    trajectory_ids = []
    time_indices = []
    step_displacements = []
    trajectory_offset = 0

    for batch in loader:
        velocities = batch["velocities"].to(device)
        init_place = batch["init_place"].to(device)
        outputs = model(velocities, init_place=init_place)
        hidden_seq = outputs["hidden_seq"]
        if selected_units is not None:
            unit_tensor = torch.as_tensor(selected_units, dtype=torch.long, device=hidden_seq.device)
            hidden_seq = torch.index_select(hidden_seq, dim=-1, index=unit_tensor)

        batch_positions = batch["positions"]
        batch_size, seq_len = batch_positions.shape[:2]
        positions.append(batch_positions.reshape(-1, 2).cpu().numpy().astype(np.float32))
        hidden.append(
            hidden_seq.reshape(-1, hidden_seq.shape[-1]).cpu().numpy().astype(np.float32)
        )
        headings.append(batch["headings"].reshape(-1).cpu().numpy().astype(np.float32))
        trajectory_ids.append(
            np.repeat(
                np.arange(trajectory_offset, trajectory_offset + batch_size, dtype=np.int64),
                seq_len,
            )
        )
        time_indices.append(np.tile(np.arange(seq_len, dtype=np.int64), batch_size))
        step_displacements.append(
            torch.linalg.vector_norm(batch["velocities"], dim=-1)
            .reshape(-1)
            .cpu()
            .numpy()
            .astype(np.float32)
        )
        trajectory_offset += batch_size

    arrays = {
        "positions": np.concatenate(positions, axis=0),
        "hidden": np.concatenate(hidden, axis=0),
        "headings": np.concatenate(headings, axis=0),
        "trajectory_ids": np.concatenate(trajectory_ids, axis=0),
        "time_indices": np.concatenate(time_indices, axis=0),
        "step_displacements": np.concatenate(step_displacements, axis=0),
    }
    if selected_units is not None:
        arrays["unit_indices"] = selected_units.astype(np.int64, copy=False)
    return arrays


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, help="Navigation training YAML")
    parser.add_argument("--checkpoint", required=True, help="Locked navigation checkpoint")
    parser.add_argument(
        "--nav_analysis_dir",
        default=None,
        help=(
            "Formal analyze_torus output. When supplied, export only its selected "
            "grid-module units and store their global unit_indices."
        ),
    )
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--num_trajectories", type=int, default=64)
    parser.add_argument("--seq_len", type=int, default=500)
    parser.add_argument("--batch_size", type=int, default=16)
    parser.add_argument(
        "--trajectory_seed_offset",
        type=int,
        default=30001,
        help=(
            "Added to the navigation training seed. The Exp1 topology export uses "
            "+20001, so +30001 is disjoint by construction."
        ),
    )
    parser.add_argument("--device", default=None)
    args = parser.parse_args()

    if args.num_trajectories < 2:
        raise ValueError("--num_trajectories must be at least 2")
    if args.seq_len < 2:
        raise ValueError("--seq_len must be at least 2")

    cfg = load_config(args.config)
    if args.device is not None:
        cfg["device"] = args.device
    cfg["output_dir"] = args.output_dir
    set_seed(
        int(cfg["seed"]),
        deterministic_algorithms=bool(
            cfg.get("runtime", {}).get("deterministic_algorithms", False)
        ),
    )
    device = configure_runtime(cfg)
    output_dir = prepare_output_dir(args.output_dir)
    logger = get_logger("export_navigation_calibration", output_dir / "export.log")
    save_config_snapshot(cfg, output_dir)
    save_run_provenance(output_dir, "export_navigation_calibration", cfg=cfg)

    checkpoint_path = Path(args.checkpoint)
    if not checkpoint_path.exists():
        raise FileNotFoundError(checkpoint_path)
    selected_units = _load_selected_units(args.nav_analysis_dir)
    trajectory_seed = int(cfg["seed"]) + int(args.trajectory_seed_offset)

    logger.info(
        "Generating %d independent navigation trajectories x %d steps; trajectory_seed=%d",
        args.num_trajectories,
        args.seq_len,
        trajectory_seed,
    )
    if selected_units is not None:
        logger.info("Saving compact hidden activity for %d selected units", selected_units.size)
    else:
        logger.warning(
            "No --nav_analysis_dir supplied; exporting all %d hidden units, which may be large",
            int(cfg["model"]["hidden_dim"]),
        )

    loader = _make_loader(
        cfg,
        num_trajectories=args.num_trajectories,
        seq_len=args.seq_len,
        batch_size=args.batch_size,
        trajectory_seed=trajectory_seed,
    )
    model = _make_model(cfg, device)
    checkpoint = load_checkpoint(checkpoint_path, map_location=device)
    if "model_state" not in checkpoint:
        raise KeyError(f"{checkpoint_path} lacks model_state")
    model.load_state_dict(checkpoint["model_state"])

    arrays = _extract_arrays(
        model,
        loader,
        device,
        selected_units=selected_units,
    )
    output_path = output_dir / "navigation_calibration_arrays.npz"
    np.savez_compressed(output_path, **arrays)

    burn_in = int(cfg.get("analysis", {}).get("torus", {}).get("burn_in_steps", 50))
    movement_threshold = float(
        cfg.get("analysis", {}).get("torus", {}).get("min_step_displacement", 0.0005)
    )
    post_filter = (
        (arrays["time_indices"] >= burn_in)
        & (arrays["step_displacements"] > movement_threshold)
    )
    summary = {
        "artifact": str(output_path.resolve()),
        "checkpoint": str(checkpoint_path.resolve()),
        "checkpoint_sha256": sha256_file(checkpoint_path),
        "navigation_seed": int(cfg["seed"]),
        "trajectory_seed": int(trajectory_seed),
        "trajectory_seed_offset": int(args.trajectory_seed_offset),
        "num_trajectories": int(args.num_trajectories),
        "seq_len": int(args.seq_len),
        "n_states": int(arrays["hidden"].shape[0]),
        "n_saved_units": int(arrays["hidden"].shape[1]),
        "compact_selected_units": selected_units is not None,
        "burn_in_steps": burn_in,
        "min_step_displacement": movement_threshold,
        "states_after_default_filter": int(post_filter.sum()),
    }
    write_json(summary, output_dir / "calibration_export_summary.json")
    logger.info("Saved %s", output_path)
    logger.info("States remaining after default source filter: %d", int(post_filter.sum()))


if __name__ == "__main__":
    main()
